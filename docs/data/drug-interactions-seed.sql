-- ============================================================================
-- بيانات مرجعية: قاعدة تداخلات دوائية أولية (starter dataset)
-- ============================================================================
-- ملف مرجعي جاهز للتبني — ليس ترحيلًا نشطًا. عند قرار التبني:
--   انسخه إلى supabase/migrations/2026MMDDNNNNNN_drug_interactions.sql
--
-- مطابقة مقفلة على الكود الفعلي:
--   * المصدر: medications.scientific_name (VARCHAR 255 — أسماء عربية)
--   * توحيد: دالة normalize_arabic() الموجودة في 20260711000300_catalog_schema.sql
--   * كل مفتاح (key) هنا = كلمة عربية "مفردة" **بعد التطبيع** (بدون أ/إ/آ — تصبح ا،
