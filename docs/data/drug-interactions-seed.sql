-- ----------------------------------------------------------------------------
-- 4) دالة الفحص — المدخل: مصفوفة أسماء علمية (نفس نص scientific_name كما هو،
--    عربي أو إنجليزي، مع جرعات أو تركيبات "أ + ب" — تُطبَّع وتُجزّأ تلقائيًا)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_drug_interactions(p_scientific_names TEXT[])
RETURNS TABLE (
    severity      TEXT,
    side_a        TEXT,
    side_b        TEXT,
    mechanism_ar  TEXT,
    management_ar TEXT,
    source        TEXT
)
LANGUAGE plpgsql STABLE AS $$
BEGIN
    RETURN QUERY
    WITH tokens AS (
        -- تجزئة كل scientific_name إلى كلمات، وتطبيعها، وإزالة أداة التعريف "ال"
        SELECT DISTINCT
            CASE WHEN length(t) > 3 AND left(t, 2) = 'ال'
                 THEN substr(t, 3) ELSE t END AS k
        FROM (
            SELECT unnest(string_to_array(
                regexp_replace(normalize_arabic(s), '[+،,/()\[\]-]', ' ', 'g'), ' '
            )) AS t
            FROM unnest(p_scientific_names) s
        ) x
        WHERE t <> '' AND length(t) > 1
    ),
    present_ing AS (
        SELECT i.key, i.label_ar
        FROM tokens JOIN ddi_ingredients i ON i.key = tokens.k
    ),
    present_groups AS (
        SELECT DISTINCT gm.group_key
        FROM present_ing JOIN ddi_group_members gm ON gm.ingredient_key = present_ing.key
    ),
    hits AS (
        SELECT p.*
        FROM ddi_pairs p
        WHERE p.is_active AND NOT p.is_deleted
          AND (
              (p.entity_a_type = 'ingredient' AND p.entity_a_key IN (SELECT key FROM present_ing))
           OR (p.entity_a_type = 'group'      AND p.entity_a_key IN (SELECT group_key FROM present_groups))
          )
          AND (
              (p.entity_b_type = 'ingredient' AND p.entity_b_key IN (SELECT key FROM present_ing))
           OR (p.entity_b_type = 'group'      AND p.entity_b_key IN (SELECT group_key FROM present_groups))
          )
    )
    SELECT DISTINCT ON (h.id)
        h.severity,
        COALESCE(ia.label_ar, ga.label_ar, h.entity_a_key),
        COALESCE(ib.label_ar, gb.label_ar, h.entity_b_key),
        h.mechanism_ar,
        h.management_ar,
        h.source
    FROM hits h
    LEFT JOIN ddi_ingredients ia ON h.entity_a_type = 'ingredient' AND ia.key = h.entity_a_key
    LEFT JOIN ddi_groups      ga ON h.entity_a_type = 'group'      AND ga.key = h.entity_a_key
    LEFT JOIN ddi_ingredients ib ON h.entity_b_type = 'ingredient' AND ib.key = h.entity_b_key
    LEFT JOIN ddi_groups      gb ON h.entity_b_type = 'group'      AND gb.key = h.entity_b_key
    ORDER BY h.id,
             CASE h.severity WHEN 'major' THEN 1 WHEN 'moderate' THEN 2 ELSE 3 END;
END;
$$;

COMMENT ON FUNCTION check_drug_interactions(TEXT[]) IS
'فحص تداخلات على أسماء علمية خام من medications.scientific_name — أداة مساعدة: القرار النهائي للصيدلي.';

