--     scientific_name إلى كلمات فتغطي التركيبات ("أموكسيسيلين كلافولانيك") تلقائيًا.
--
-- المنهجية:
--   * أزواج مجمعة عبر "فئات" (nsaid، macrolide …) + أزواج خاصة بدقة أعلى.
--   * الشدة: major (شديد) / moderate (متوسط) — أغلبها مستخرج من نشرات FDA
--     وقائمة ONCHigh عالية الخطورة.
--   * ⚠️ بيانات أولية تشترط مراجعة صيدلي مختص قبل الاعتماد الإنتاجي،
--     والتنبيه في المنتج دائمًا "مساعد قرار" والقرار النهائي للصيدلي.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1) قاموس المواد الفعالة (key = بعد normalize_arabic — مفردة واحدة)
--    notes_ar = تنبيه فردية تُعرض دائمًا مع الصنف (لا تحتاج زوجًا).
-- ----------------------------------------------------------------------------
