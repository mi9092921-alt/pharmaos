-- ----------------------------------------------------------------------------
-- 3) أزواج التداخل — entity_*_type: ingredient | group
--    الشدة: major | moderate
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ddi_pairs (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    entity_a_type  TEXT NOT NULL CHECK (entity_a_type IN ('ingredient', 'group')),
    entity_a_key   TEXT NOT NULL,
    entity_b_type  TEXT NOT NULL CHECK (entity_b_type IN ('ingredient', 'group')),
    entity_b_key   TEXT NOT NULL,
    severity       TEXT NOT NULL CHECK (severity IN ('major', 'moderate', 'minor')),
    mechanism_ar   TEXT NOT NULL,
    management_ar  TEXT NOT NULL,
    source         TEXT NOT NULL DEFAULT 'fda_label',   -- fda_label | onchigh | literature
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    is_deleted     BOOLEAN NOT NULL DEFAULT FALSE,
    sync_version   BIGINT NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ddi_pairs_not_self CHECK (NOT (entity_a_type = entity_b_type AND entity_a_key = entity_b_key))
);

CREATE INDEX IF NOT EXISTS idx_ddi_pairs_a ON ddi_pairs (entity_a_type, entity_a_key) WHERE is_active AND NOT is_deleted;
CREATE INDEX IF NOT EXISTS idx_ddi_pairs_b ON ddi_pairs (entity_b_type, entity_b_key) WHERE is_active AND NOT is_deleted;

