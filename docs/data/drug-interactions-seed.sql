CREATE OR REPLACE FUNCTION check_drug_interactions_by_ids(p_medication_ids UUID[])
RETURNS TABLE (
    severity      TEXT,
    side_a        TEXT,
    side_b        TEXT,
    mechanism_ar  TEXT,
    management_ar TEXT,
    source        TEXT
)
LANGUAGE SQL STABLE AS $$
    SELECT * FROM check_drug_interactions(
        ARRAY(
            SELECT scientific_name
            FROM medications
            WHERE id = ANY(p_medication_ids)
              AND scientific_name IS NOT NULL
              AND NOT is_deleted
        )
    );
$$;

